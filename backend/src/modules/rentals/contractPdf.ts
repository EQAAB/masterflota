import type { QueryResultRow } from "pg";

type Db = {
  query: <T extends QueryResultRow = QueryResultRow>(
    text: string,
    params?: unknown[],
  ) => Promise<{ rows: T[] }>;
};

/** Minimal text contract for MVP — replace with pdfkit when dependency is added. */
export async function buildContractText(
  db: Db,
  orgId: string,
  bookingId: string,
): Promise<string | null> {
  const { rows } = await db.query<{
    booking_number: string;
    start_at: Date;
    end_at: Date;
    total_amount: string;
    currency: string;
    customer_name: string;
    license_plate: string;
    make: string;
    model: string;
  }>(
    `SELECT b.booking_number, b.start_at, b.end_at, b.total_amount, b.currency,
            c.legal_name AS customer_name,
            v.license_plate, v.make, v.model
     FROM rental_bookings b
     JOIN rental_customers c ON c.id = b.customer_id
     JOIN vehicles v ON v.id = b.vehicle_id
     WHERE b.id = $1::uuid AND b.organization_id = $2::uuid`,
    [bookingId, orgId],
  );
  const b = rows[0];
  if (!b) return null;

  return [
    "VEHICLE RENTAL AGREEMENT",
    "========================",
    "",
    `Booking: ${b.booking_number}`,
    `Customer: ${b.customer_name}`,
    `Vehicle: ${b.make} ${b.model} (${b.license_plate})`,
    `Period: ${new Date(b.start_at).toISOString().slice(0, 10)} – ${new Date(b.end_at).toISOString().slice(0, 10)}`,
    `Total: ${b.total_amount} ${b.currency}`,
    "",
    "Terms: Vehicle must be returned in agreed condition. Deposit may apply.",
    "Generated by Fleet Manager.",
  ].join("\n");
}
